CREATE TABLE IF NOT EXISTS public.smart_diagnostic_ai_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id uuid NOT NULL REFERENCES public.providers(id) ON DELETE RESTRICT,
  session_id uuid REFERENCES public.smart_diagnostic_sessions(id) ON DELETE SET NULL,
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  provider text NOT NULL,
  model text NOT NULL,
  operation text NOT NULL,
  latency_ms integer,
  input_tokens integer,
  output_tokens integer,
  total_tokens integer,
  estimated_cost numeric,
  success boolean NOT NULL,
  fallback_used boolean NOT NULL DEFAULT false,
  fallback_reason text,
  error_code text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_ai_usage_provider_created
  ON public.smart_diagnostic_ai_usage(provider_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_ai_usage_session
  ON public.smart_diagnostic_ai_usage(session_id, created_at DESC)
  WHERE session_id IS NOT NULL;

