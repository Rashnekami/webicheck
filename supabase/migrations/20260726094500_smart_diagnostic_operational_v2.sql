GRANT SELECT ON public.smart_diagnostic_ai_usage TO authenticated;
GRANT ALL ON public.smart_diagnostic_ai_usage TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.smart_diagnostic_ai_usage_id_seq TO authenticated, service_role;

DROP POLICY IF EXISTS smart_diagnostic_ai_usage_admin_read ON public.smart_diagnostic_ai_usage;
CREATE POLICY smart_diagnostic_ai_usage_admin_read
ON public.smart_diagnostic_ai_usage FOR SELECT TO authenticated
USING (provider_id = public.current_provider_id() AND public.has_role(auth.uid(), 'admin'));

