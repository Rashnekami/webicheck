CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_learning_provider
  ON public.smart_diagnostic_learning_cases(provider_id, validated_at DESC)
  WHERE validated_for_learning IS TRUE;

CREATE OR REPLACE FUNCTION public.protect_validated_smart_diagnostic()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF OLD.validated_for_learning IS TRUE THEN
    RAISE EXCEPTION 'smart_diagnostic_validated_snapshot_immutable';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_validated_smart_diagnostic
  ON public.smart_diagnostic_sessions;
CREATE TRIGGER trg_protect_validated_smart_diagnostic
BEFORE UPDATE ON public.smart_diagnostic_sessions
FOR EACH ROW
WHEN (OLD.validated_for_learning IS TRUE)
EXECUTE FUNCTION public.protect_validated_smart_diagnostic();

ALTER TABLE public.smart_diagnostic_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_measurements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_ai_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_diagnostic_learning_cases ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON
  public.smart_diagnostic_settings,
  public.smart_diagnostic_sessions,
  public.smart_diagnostic_events,
  public.smart_diagnostic_measurements,
  public.smart_diagnostic_evidence,
  public.smart_diagnostic_ai_reviews,
  public.smart_diagnostic_learning_cases
FROM PUBLIC, anon;

GRANT SELECT, INSERT, UPDATE ON public.smart_diagnostic_sessions TO authenticated;
GRANT SELECT, INSERT ON
  public.smart_diagnostic_events,
  public.smart_diagnostic_evidence,
  public.smart_diagnostic_ai_reviews
TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.smart_diagnostic_measurements TO authenticated;
GRANT SELECT ON public.smart_diagnostic_settings, public.smart_diagnostic_learning_cases
TO authenticated;
GRANT INSERT, UPDATE ON public.smart_diagnostic_learning_cases TO authenticated;
GRANT ALL ON
  public.smart_diagnostic_settings,
  public.smart_diagnostic_sessions,
  public.smart_diagnostic_events,
  public.smart_diagnostic_measurements,
  public.smart_diagnostic_evidence,
  public.smart_diagnostic_ai_reviews,
  public.smart_diagnostic_learning_cases
TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
  public.smart_diagnostic_events_id_seq,
  public.smart_diagnostic_measurements_id_seq
TO authenticated, service_role;

