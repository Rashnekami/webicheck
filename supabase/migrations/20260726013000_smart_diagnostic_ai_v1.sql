CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_ai_reviews_session
  ON public.smart_diagnostic_ai_reviews(session_id, analyzed_at DESC);

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_learning_cases (
