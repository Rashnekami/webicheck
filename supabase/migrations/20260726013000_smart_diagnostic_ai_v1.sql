CREATE TABLE IF NOT EXISTS public.smart_diagnostic_settings (
  provider_id uuid PRIMARY KEY REFERENCES public.providers(id) ON DELETE CASCADE,
  optical_rx_min_dbm numeric,
  optical_rx_max_dbm numeric,
  noc_whatsapp_e164 text,
  ai_enabled boolean NOT NULL DEFAULT false,
  learning_enabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    optical_rx_min_dbm IS NULL
    OR optical_rx_max_dbm IS NULL
    OR optical_rx_min_dbm < optical_rx_max_dbm
  ),
  CHECK (noc_whatsapp_e164 IS NULL OR noc_whatsapp_e164 ~ '^55[1-9][0-9]{9,10}$')
);

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_sessions (
  id uuid PRIMARY KEY,
  provider_id uuid NOT NULL REFERENCES public.providers(id) ON DELETE RESTRICT,
  technician_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  checklist_id uuid REFERENCES public.checklists(id) ON DELETE SET NULL,
  case_id uuid,
  checklist_code text,
  service_order text,
  client_name text,
  city text,
  service_type text NOT NULL DEFAULT 'manutencao'
    CHECK (service_type IN ('manutencao')),
  equipment_model text,
  engine_version text NOT NULL,
  status text NOT NULL,
  symptom_codes jsonb NOT NULL DEFAULT '[]'::jsonb,
  answers_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  deterministic_evaluation jsonb NOT NULL DEFAULT '{}'::jsonb,
  decision_path jsonb NOT NULL DEFAULT '[]'::jsonb,
  validated_for_learning boolean NOT NULL DEFAULT false,
  validated_by uuid REFERENCES auth.users(id) ON DELETE RESTRICT,
  validated_at timestamptz,
  started_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_provider_updated
  ON public.smart_diagnostic_sessions(provider_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_technician_updated
  ON public.smart_diagnostic_sessions(technician_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_checklist
  ON public.smart_diagnostic_sessions(checklist_id, updated_at DESC)
  WHERE checklist_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_case
  ON public.smart_diagnostic_sessions(case_id, updated_at DESC)
  WHERE case_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES public.smart_diagnostic_sessions(id) ON DELETE RESTRICT,
  client_event_id uuid NOT NULL,
  question_id text NOT NULL,
  question_text text NOT NULL,
  category text NOT NULL,
  answer jsonb NOT NULL,
  answer_label text NOT NULL,
  evidence_label text,
  origin text NOT NULL CHECK (origin IN ('technician','webi-diagnostic','system')),
  engine_version text NOT NULL,
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  event_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (session_id, client_event_id)
);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_events_session
  ON public.smart_diagnostic_events(session_id, event_at);

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_measurements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES public.smart_diagnostic_sessions(id) ON DELETE RESTRICT,
  metric_key text NOT NULL,
  numeric_value numeric,
  text_value text,
  unit text,
  source text NOT NULL DEFAULT 'technician',
  measured_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (session_id, metric_key),
  CHECK (numeric_value IS NOT NULL OR text_value IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_measurements_session
  ON public.smart_diagnostic_measurements(session_id, measured_at);

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_evidence (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES public.smart_diagnostic_sessions(id) ON DELETE RESTRICT,
  event_id bigint REFERENCES public.smart_diagnostic_events(id) ON DELETE RESTRICT,
  evidence_type text NOT NULL,
  storage_path text,
  external_reference text,
  sha256 text,
  source text NOT NULL DEFAULT 'technician',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  recorded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  CHECK (storage_path IS NOT NULL OR external_reference IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_smart_diagnostic_evidence_session
  ON public.smart_diagnostic_evidence(session_id, recorded_at);

CREATE TABLE IF NOT EXISTS public.smart_diagnostic_ai_reviews (
